"""Content/environment contract for reusing a completed CPU verification.

Only capture_environment imports project or numerical packages. Git HEAD is
evidence, not the reuse criterion: documentation commits do not change this
contract. All checks are explicit and remain active with ``python -O``.
"""
from __future__ import annotations

import hashlib
from importlib import metadata
import json
import os
from pathlib import Path, PurePosixPath
import platform
import re
import subprocess
import sys
import sysconfig
from urllib.parse import parse_qs, quote, unquote, urlsplit


REQUIRED_CHECKS = ('pip_check', 'pip_freeze', 'tests', 'legacy_tests', 'cli_help')
IMPORT_ENVIRONMENT_FIELDS = ('python', 'python_executable', 'prefix', 'base_prefix',
                             'numpy', 'torch', 'cuda_build', 'package_sources')
PROJECT_DISTRIBUTION = 'mtad-association-pilot'


def _root_path(root):
    root = Path(root).resolve()
    if not root.is_dir():
        raise ValueError(f'Repository root is not a directory: {root}')
    return root


def _digest(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(chunk)
    return result.hexdigest()


def _canonical(value):
    try:
        return json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False)
    except (TypeError, ValueError) as exc:
        raise ValueError('Contract evidence must contain finite JSON values') from exc


def _read_text(path):
    try:
        return Path(path).read_text(encoding='utf-8').strip()
    except (OSError, UnicodeError) as exc:
        raise ValueError(f'Missing or unreadable CPU receipt file: {path}') from exc


def _read_json(path):
    try:
        value = json.loads(_read_text(path))
    except json.JSONDecodeError as exc:
        raise ValueError(f'Invalid JSON CPU receipt file: {path}') from exc
    if not isinstance(value, dict):
        raise ValueError(f'Expected a JSON object in CPU receipt: {path}')
    _canonical(value)
    return value


def source_manifest(root) -> dict:
    """Hash the complete execution-file set; additions and deletions matter.

    Matches ENV004's scope: association/tests *.py, configs *.json, tools
    *.py/*.sh, and pyproject.toml. Documentation and generated bytecode are
    excluded. Symlink directories and files escaping the repository are rejected.
    """
    root = _root_path(root)
    paths = {root / 'pyproject.toml'}
    scopes = {'association': {'.py'}, 'tests': {'.py'}, 'configs': {'.json'},
              'tools': {'.py', '.sh'}}
    for name, suffixes in scopes.items():
        directory = root / name
        if directory.is_symlink():
            raise ValueError(f'Symlink source directory is not supported: {directory}')
        if not directory.exists():
            continue
        if not directory.is_dir():
            raise ValueError(f'Source scope is not a directory: {directory}')
        for base, directories, files in os.walk(directory, followlinks=False):
            for child in directories:
                path = Path(base) / child
                if path.is_symlink():
                    raise ValueError(f'Symlink source directory is not supported: {path}')
            paths.update(Path(base) / name for name in files if Path(name).suffix in suffixes)
    result = {}
    for path in sorted(paths):
        if not path.is_file():
            raise ValueError(f'Source file is missing or is not regular: {path}')
        if not path.resolve().is_relative_to(root):
            raise ValueError(f'Source file resolves outside repository: {path}')
        result[path.relative_to(root).as_posix()] = _digest(path)
    return result


def _package_source(package):
    source = getattr(package, '__file__', None)
    if not source:
        raise ValueError(f'Package has no source location: {package.__name__}')
    source = Path(source).resolve()
    if not source.is_file():
        raise ValueError(f'Package source does not exist: {source}')
    return source


def _distribution_name(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def _local_file_url(url):
    parsed = urlsplit(url)
    if parsed.scheme != 'file' or parsed.netloc not in ('', 'localhost') or parsed.query:
        return None
    return Path(unquote(parsed.path)).resolve()


def _verified_project_editable(root):
    """Return installed metadata only for the known project edited from this root."""
    try:
        distribution = metadata.distribution(PROJECT_DISTRIBUTION)
        if _distribution_name(distribution.metadata.get('Name', '')) != PROJECT_DISTRIBUTION:
            return None
        direct = json.loads(distribution.read_text('direct_url.json') or '{}')
        if not isinstance(direct, dict) or direct.get('dir_info', {}).get('editable') is not True:
            return None
        if _local_file_url(direct.get('url', '')) != root:
            return None
        version = distribution.version
        if not isinstance(version, str) or not version.strip() or '\n' in version or '\r' in version:
            return None
        return version
    except (metadata.PackageNotFoundError, OSError, TypeError, ValueError, AttributeError):
        return None


def normalize_freeze(root, lines) -> list:
    """Normalize only this verified editable project's incidental Git HEAD.

    pip may render a local editable checkout as a VCS URL pinned to its current
    HEAD, even when only documentation changed. Replace that one entry with its
    real checkout URI, distribution identity and installed metadata version.
    Execution contents remain bound by source_manifest. Unverified entries and
    all other dependency VCS pins retain their original values.
    """
    root = _root_path(root)
    if isinstance(lines, str):
        lines = lines.splitlines()
    result = []
    checked = False
    project_version = None
    for line in lines:
        line = line.strip()
        if not line:
            continue
        editable = re.fullmatch(r'(?:-e|--editable)\s+(.+)', line)
        candidate = False
        if editable:
            value = editable.group(1)
            parsed = urlsplit(value)
            names = parse_qs(parsed.fragment).get('egg', [])
            project_name = len(names) == 1 and _distribution_name(names[0]) == PROJECT_DISTRIBUTION
            if parsed.scheme == 'file':
                candidate = _local_file_url(value) == root and (not names or project_name)
            elif project_name and parsed.scheme.startswith(('git+', 'hg+', 'svn+', 'bzr+')):
                candidate = True
            elif not names:
                if not parsed.scheme and not parsed.fragment:
                    path = Path(value)
                    candidate = path.is_absolute() and path.resolve() == root
        if candidate:
            if not checked:
                project_version = _verified_project_editable(root)
                checked = True
            if project_version is not None:
                version = quote(project_version, safe='._+-!')
                line = f'-e {root.as_uri()}#egg={PROJECT_DISTRIBUTION}=={version}'
        result.append(line)
    return sorted(result)


def capture_environment(root) -> dict:
    """Capture reuse-sensitive settings without GPU probes, installs or downloads."""
    root = _root_path(root)
    import numpy
    import torch
    import association

    prefix = Path(sys.prefix).resolve()
    sources = {package.__name__: _package_source(package)
               for package in (numpy, torch, association)}
    expected = root / 'association' / '__init__.py'
    if sources['association'] != expected or not expected.is_file():
        raise ValueError('association must be imported from the current repository root')
    for name in ('numpy', 'torch'):
        if not sources[name].is_relative_to(prefix):
            raise ValueError(f'{name} must be imported from the current Python prefix')

    pip_env = {key: value for key, value in os.environ.items() if not key.startswith('PIP_')}
    pip_env.update(PIP_CONFIG_FILE=os.devnull, PIP_NO_INDEX='1', PIP_DISABLE_PIP_VERSION_CHECK='1')
    try:
        freeze = subprocess.run(
            [sys.executable, '-m', 'pip', '--disable-pip-version-check', 'freeze', '--all'],
            cwd=root, env=pip_env, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError('Unable to capture local pip freeze within 60 seconds') from exc
    if freeze.returncode != 0:
        raise RuntimeError(f'Local pip freeze failed with exit code {freeze.returncode}')

    custom = sys.modules.get('sitecustomize')
    loaded = custom is not None
    custom_file = getattr(custom, '__file__', None) if loaded else None
    custom_path = (Path(custom_file) if custom_file else
                   Path(sysconfig.get_path('purelib')) / 'sitecustomize.py').resolve()
    exists = custom_path.is_file()
    result = {
        'schema_version': 1,
        'python': platform.python_version(),
        'python_executable': str(Path(sys.executable).absolute()),
        'prefix': str(prefix),
        'base_prefix': str(Path(sys.base_prefix).resolve()),
        'numpy': str(numpy.__version__),
        'torch': str(torch.__version__),
        'cuda_build': torch.version.cuda,
        'package_sources': {name: str(path) for name, path in sources.items()},
        'pip_freeze': normalize_freeze(root, freeze.stdout.splitlines()),
        'sitecustomize': {'loaded': loaded, 'path': str(custom_path), 'exists': exists,
                          'sha256': _digest(custom_path) if exists else None},
        'thread_settings': {name: os.environ.get(name) for name in ('OMP_NUM_THREADS', 'MKL_NUM_THREADS')},
        'torch_precision': {
            'float32_matmul_precision': torch.get_float32_matmul_precision(),
            'cuda_matmul_allow_tf32': torch.backends.cuda.matmul.allow_tf32,
            'cudnn_allow_tf32': torch.backends.cudnn.allow_tf32,
        },
    }
    _canonical(result)
    return result


def validate_cpu_receipt(root, cpu_dir, environment) -> dict:
    """Require intact successful CPU evidence and identical current execution inputs.

    environment must be a fresh capture_environment(root) result. Legacy ENV004
    evidence lacks the environment snapshot/recheck binding and is not migrated.
    The current HEAD may differ from the CPU commit when only documents changed.
    """
    root = _root_path(root)
    cpu_dir = Path(cpu_dir)
    if not cpu_dir.is_absolute():
        cpu_dir = root / cpu_dir
    cpu_dir = cpu_dir.resolve()
    if not (cpu_dir / 'environment.json').is_file():
        raise ValueError('Fresh CPU verification required: environment.json is missing; '
                         'legacy ENV004 receipts cannot be reused')
    for name in ('setup_exit_code.txt', 'setup_wrapper_exit_code.txt'):
        if _read_text(cpu_dir / name) != '0':
            raise ValueError(f'CPU verification failed: {name} is not 0')
    if _read_text(cpu_dir / 'setup_completed.txt') != 'completed':
        raise ValueError('CPU verification has no completed marker')

    report = _read_json(cpu_dir / 'validation.json')
    if report.get('status') != 'COMPLETED':
        raise ValueError('CPU validation status is not COMPLETED')
    cpu_commit = _read_text(cpu_dir / 'actual_commit.txt')
    if not re.fullmatch(r'[a-fA-F0-9]{40}|[a-fA-F0-9]{64}', cpu_commit):
        raise ValueError('CPU actual_commit is not a full Git object ID')
    if report.get('actual_commit') != cpu_commit:
        raise ValueError('CPU actual_commit and validation report disagree')
    checks = report.get('checks')
    if not isinstance(checks, dict) or not set(REQUIRED_CHECKS).issubset(checks):
        raise ValueError('CPU validation report is missing required checks')
    for name, code in checks.items():
        if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_-]+', name):
            raise ValueError('Invalid CPU check name')
        if type(code) is not int or code != 0 or _read_text(cpu_dir / f'{name}_exit_code.txt') != '0':
            raise ValueError(f'CPU check did not pass: {name}')

    imported = _read_json(cpu_dir / 'import_check.json')
    if _canonical(imported) != _canonical(report.get('import_check')):
        raise ValueError('CPU import_check and validation report disagree')
    stored_environment = _read_json(cpu_dir / 'environment.json')
    if not isinstance(environment, dict) or _canonical(stored_environment) != _canonical(environment):
        raise ValueError('Environment changed after CPU verification; fresh CPU verification required')
    frozen_packages = normalize_freeze(root, _read_text(cpu_dir / 'pip_freeze.txt').splitlines())
    if stored_environment.get('pip_freeze') != frozen_packages:
        raise ValueError('CPU pip_freeze.txt disagrees with environment snapshot')
    for name in IMPORT_ENVIRONMENT_FIELDS:
        if name not in imported or name not in stored_environment:
            raise ValueError(f'CPU import/environment evidence is missing {name}')
        if _canonical(imported[name]) != _canonical(stored_environment[name]):
            raise ValueError(f'CPU import_check disagrees with environment snapshot: {name}')

    manifest = _read_json(cpu_dir / 'source_files.json')
    for name, value in manifest.items():
        path = PurePosixPath(name)
        if (not name or '\\' in name or path.is_absolute() or '..' in path.parts or
                path.as_posix() != name or not isinstance(value, str) or
                not re.fullmatch(r'[a-f0-9]{64}', value)):
            raise ValueError('Invalid source manifest path or SHA256')
    current = source_manifest(root)
    if manifest != current:
        added = sorted(current.keys() - manifest.keys())
        deleted = sorted(manifest.keys() - current.keys())
        modified = sorted(name for name in manifest.keys() & current.keys() if manifest[name] != current[name])
        raise ValueError(f'Execution source manifest changed: added={added}, deleted={deleted}, modified={modified}')
    source_hash = _digest(cpu_dir / 'source_files.json')
    environment_hash = _digest(cpu_dir / 'environment.json')
    if report.get('environment_rechecked') is not True:
        raise ValueError('Fresh CPU verification required: environment was not rechecked at acceptance')
    if report.get('source_files_sha256') != source_hash:
        raise ValueError('CPU source manifest hash binding does not match validation report')
    if report.get('environment_sha256') != environment_hash:
        raise ValueError('CPU environment hash binding does not match validation report')

    try:
        head = subprocess.run(['git', '-C', str(root), 'rev-parse', 'HEAD'],
                              capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError('Unable to record current Git HEAD') from exc
    if head.returncode != 0:
        raise RuntimeError('Unable to record current Git HEAD')
    return {'directory': str(cpu_dir), 'cpu_actual_commit': cpu_commit,
            'current_commit': head.stdout.strip(),
            'validation_sha256': _digest(cpu_dir / 'validation.json'),
            'source_files_sha256': source_hash, 'environment_sha256': environment_hash}
